# AzureEntraStarter smoke test (Windows PowerShell 5+ / pwsh):
#   1. publishes the app,
#   2. checks that Production refuses an insecure configuration,
#   3. runs the real server (Kestrel over HTTPS, SQL Server LocalDB with migrations) configured against the REAL
#      Microsoft Entra endpoints (discovery from login.microsoftonline.com) and sends real HTTP requests: the sign-in
#      start reaches Microsoft's authorize endpoint, and Microsoft's own answer is checked.
# Requirements: .NET 10 SDK, SQL Server LocalDB (installed with Visual Studio), internet.
# Usage (from the repo root):  powershell -ExecutionPolicy Bypass -File scripts\smoke-test.ps1
$ErrorActionPreference = 'Continue'   # native stderr must not abort the script on Windows PowerShell 5
$repo = Join-Path $PSScriptRoot '..' | Resolve-Path
$work = Join-Path $repo 'artifacts\smoke'
$pub  = Join-Path $work 'publish'
New-Item -ItemType Directory -Force -Path $work | Out-Null
$fail = 0
function Check($name, $cond) { if ($cond) { "PASS $name" } else { "FAIL $name"; $script:fail++ } }

"==== publish ===="
dotnet publish (Join-Path $repo 'src\AzureEntraStarter.Server') -c Release -o $pub -nologo -v:minimal 2>&1 | Select-Object -Last 5
Check 'publish copied Angular into wwwroot' (Test-Path (Join-Path $pub 'wwwroot\index.html'))
# A throwaway P-256 key for this run, generated by the application itself (never a real one)
$signingKey = (& dotnet (Join-Path $pub 'AzureEntraStarter.Server.dll') --generate-signing-key | Out-String).Trim()
Check '--generate-signing-key prints a P-256 key' ($signingKey.Length -gt 100 -and $signingKey -match '^[A-Za-z0-9+/=]+$')

"==== Production must refuse an insecure configuration ===="
$env:ASPNETCORE_ENVIRONMENT = 'Production'
Push-Location $pub
$out = & dotnet (Join-Path $pub 'AzureEntraStarter.Server.dll') --urls http://localhost:5398 2>&1 | Out-String
Check 'Production without a signing key refuses to start' ($out -match 'Jwt:SigningKey is required')
$env:Jwt__SigningKey = $signingKey
$out = & dotnet (Join-Path $pub 'AzureEntraStarter.Server.dll') --urls http://localhost:5398 2>&1 | Out-String
Pop-Location
Check 'Production refuses to start' ($out -match 'Insecure production configuration')
Check 'Production flags Entra not configured' ($out -match 'Authentication:Entra must be enabled')
Check 'Production flags the missing database' ($out -match 'ConnectionStrings:Default is required')
Check 'Production flags unencrypted Data Protection keys' ($out -match 'KeyVaultKeyId')
($out -split "`n" | Select-String 'Insecure| - ' | Select-Object -First 8) -join "`n"

"==== Real server (HTTPS, LocalDB) against the real Microsoft Entra endpoints ===="
dotnet dev-certs https --check --trust 2>&1 | Out-Null
Check 'ASP.NET Core development certificate is trusted' ($LASTEXITCODE -eq 0)
$clientId = [Guid]::NewGuid().ToString()
# With the Azure CLI signed in, the run uses YOUR directory id (single tenant, as in production); without it, the
# multi-tenant "organizations" authority. Only Microsoft's public endpoints are used; nothing is created in the directory.
$tenant = $null
try { $tenant = (& az account show --query tenantId -o tsv 2>$null | Out-String).Trim() } catch { }
$singleTenant = $tenant -match '^[0-9a-fA-F]{8}-([0-9a-fA-F]{4}-){3}[0-9a-fA-F]{12}$'
$authorityPath = if ($singleTenant) { $tenant } else { 'organizations' }
"Authority: https://login.microsoftonline.com/$authorityPath/v2.0 (random client id $clientId)"
$env:ASPNETCORE_ENVIRONMENT = 'Development'
$env:ConnectionStrings__Default = 'Server=(localdb)\MSSQLLocalDB;Database=AzureEntraStarterSmoke;Trusted_Connection=True;MultipleActiveResultSets=true;TrustServerCertificate=True'
$env:Authentication__Entra__Enabled = 'true'
$env:Authentication__Entra__Authority = "https://login.microsoftonline.com/$authorityPath/v2.0"
$env:Authentication__Entra__ClientId = $clientId
$env:Authentication__Entra__ClientSecret = 'smoke-test-not-a-real-secret'
if (-not $singleTenant) { $env:Authentication__Entra__AllowedTenantIds__0 = [Guid]::NewGuid().ToString() }
$log = Join-Path $work 'server.log'
$err = Join-Path $work 'server.err'
$p = Start-Process dotnet -ArgumentList "`"$(Join-Path $pub 'AzureEntraStarter.Server.dll')`" --urls https://localhost:5399" -WorkingDirectory $pub -PassThru -WindowStyle Hidden -RedirectStandardOutput $log -RedirectStandardError $err
try {
  $base = 'https://localhost:5399'
  Add-Type -AssemblyName System.Net.Http
  Add-Type -AssemblyName System.Web
  $handler = New-Object System.Net.Http.HttpClientHandler
  $handler.AllowAutoRedirect = $false
  $handler.UseCookies = $true
  $handler.CookieContainer = New-Object System.Net.CookieContainer
  $client = New-Object System.Net.Http.HttpClient($handler)
  $client.Timeout = [TimeSpan]::FromSeconds(30)
  function Send($method, $url, $headers = @{}, $body = $null) {
    $req = New-Object System.Net.Http.HttpRequestMessage([System.Net.Http.HttpMethod]::new($method), $url)
    foreach ($k in $headers.Keys) { [void]$req.Headers.TryAddWithoutValidation($k, $headers[$k]) }
    if ($body) { $req.Content = New-Object System.Net.Http.StringContent($body, [Text.Encoding]::UTF8, 'application/x-www-form-urlencoded') }
    $res = $client.SendAsync($req).GetAwaiter().GetResult()
    $text = $res.Content.ReadAsStringAsync().GetAwaiter().GetResult()
    return [pscustomobject]@{ Status = [int]$res.StatusCode; Location = $res.Headers.Location; Text = $text; Headers = $res.Headers }
  }
  $ready = $false
  for ($i = 0; $i -lt 60 -and -not $ready; $i++) { try { $ready = (Send 'GET' "$base/health/ready").Status -eq 200 } catch { Start-Sleep 1 } }

  $r = Send 'GET' "$base/health/ready";          Check 'readiness: database (LocalDB, migrated) healthy' ($r.Status -eq 200 -and $r.Text -eq 'Healthy')
  $r = Send 'GET' "$base/";                      Check 'index.html served' ($r.Status -eq 200 -and $r.Text -match 'app-root')
  Check 'index.html has a CSP without inline scripts and is not frameable' (($r.Headers.GetValues('Content-Security-Policy') -join '') -match "script-src 'self';.*frame-ancestors 'none'")
  $r = Send 'GET' "$base/profile";               Check 'SPA route served without a session' ($r.Status -eq 200 -and $r.Text -match 'app-root')
  $r = Send 'GET' "$base/api/auth/config";       Check '/api/auth/config: Entra enabled' ($r.Status -eq 200 -and $r.Text -match '"entraEnabled":true')
  $r = Send 'GET' "$base/.well-known/jwks.json"; Check 'JWKS publishes one EC public key' ($r.Status -eq 200 -and $r.Text -match '"kty":"EC"' -and -not ($r.Text -match '"d":'))
  $r = Send 'GET' "$base/api/sample/hello";      Check 'API requires a session (401)' ($r.Status -eq 401)
  $r = Send 'GET' "$base/api/does-not-exist";    Check 'unknown API route requires a session too (401)' ($r.Status -eq 401)
  $r = Send 'POST' "$base/api/auth/refresh";     Check 'refresh without Origin/XSRF refused (403)' ($r.Status -eq 403)

  # ---- The sign-in start: the server reads Microsoft's real discovery document and redirects there ----
  $r = Send 'GET' "$base/api/auth/entra/start?returnUrl=%2Fprofile"
  $auth = $r.Location
  Check 'start redirects (302)' ($r.Status -eq 302)
  Check 'redirect goes to the real Microsoft authorize endpoint (from discovery)' ($auth -and $auth.AbsoluteUri.StartsWith("https://login.microsoftonline.com/$authorityPath/oauth2/v2.0/authorize"))
  $q = [System.Web.HttpUtility]::ParseQueryString($auth.Query)
  Check 'client_id, code flow, form_post' ($q['client_id'] -eq $clientId -and $q['response_type'] -eq 'code' -and $q['response_mode'] -eq 'form_post')
  Check 'PKCE S256 + state + nonce' ($q['code_challenge_method'] -eq 'S256' -and $q['code_challenge'].Length -ge 43 -and $q['state'] -and $q['nonce'])
  Check 'redirect_uri is this host callback' ($q['redirect_uri'] -eq "$base/api/auth/oidc/callback")
  $setCookies = ($r.Headers.GetValues('Set-Cookie') -join "`n")
  Check 'correlation and nonce cookies: Secure, HttpOnly, SameSite=None' ($setCookies -match '\.AspNetCore\.Correlation\.' -and $setCookies -match '\.AspNetCore\.OpenIdConnect\.Nonce\.' -and $setCookies -match 'secure' -and $setCookies -match 'samesite=none' -and $setCookies -match 'httponly')

  # ---- Microsoft's own answer to that request ----
  $ms = Send 'GET' $auth.AbsoluteUri @{ 'User-Agent' = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36' }
  # Microsoft first answers with a "Redirecting" page (sso_reload) that a browser posts again; follow it once like a browser.
  $reload = [regex]::Match($ms.Text, '"urlPost":"(?<u>[^"]+sso_reload=True)"')
  if ($reload.Success) {
    $next = 'https://login.microsoftonline.com' + [regex]::Unescape($reload.Groups['u'].Value)
    $ms = Send 'GET' $next @{ 'User-Agent' = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36' }
  }
  $ms.Text | Set-Content -Encoding UTF8 (Join-Path $work 'microsoft-authorize.html')
  "Microsoft answered HTTP $($ms.Status)"
  # Microsoft shows its sign-in page for a well-formed request; the client id is checked once the user signs in.
  Check 'Microsoft accepted the request and shows its sign-in page' ($ms.Status -eq 200 -and $ms.Text -match '<title>Sign in to your account')
  Check 'Microsoft carries our client id and callback in its sign-in page' ($ms.Text -match [regex]::Escape($clientId) -and $ms.Text -match 'redirect_uri=https%3a%2f%2flocalhost%3a5399%2fapi%2fauth%2foidc%2fcallback')

  # ---- Forged or stray callbacks never reach a session ----
  $r = Send 'POST' "$base/api/auth/oidc/callback" @{} 'code=forged&state=forged'
  Check 'forged callback returns to sign-in with a coarse reason' ($r.Status -eq 302 -and "$($r.Location)" -match '^/login\?ssoError=sso_')
  $r = Send 'GET' "$base/api/auth/entra/complete"
  Check 'completion without a round trip returns to sign-in' ($r.Status -eq 302 -and "$($r.Location)" -eq '/login?ssoError=sso_session_expired')
  $r = Send 'POST' "$base/api/auth/entra/exchange" @{ 'Origin' = $base }
  Check 'exchange without a valid ticket refused (400/401)' ($r.Status -in 400, 401)
}
finally {
  Stop-Process -Id $p.Id -Force -ErrorAction SilentlyContinue
  foreach ($v in 'ConnectionStrings__Default', 'Jwt__SigningKey', 'Authentication__Entra__Enabled', 'Authentication__Entra__Authority', 'Authentication__Entra__ClientId', 'Authentication__Entra__ClientSecret', 'Authentication__Entra__AllowedTenantIds__0') {
    Remove-Item "Env:$v" -ErrorAction SilentlyContinue
  }
}
Check 'server logged no unhandled exception' (-not ((Get-Content $log -Raw) -match 'Unhandled exception|fail: Microsoft.AspNetCore.Server'))
"==== $fail failure(s) ===="
exit $fail
